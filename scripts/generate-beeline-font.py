#!/usr/bin/env python3
"""Generate embedded firmware masks and the complete IcoMoon code map.

Generation only: pip dependencies are listed in beeline-font-requirements.txt.
The Arduino build needs neither Python nor a font filesystem/TTF interpreter.
"""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FIRMWARE = ROOT / "artifacts/beeline-navigator/firmware"
SOURCE = FIRMWARE / "font-source"
SIZE = 96
FONT_SIZE = 96
ACTIVE = (
    ("straight", "nav_direction_continue_straight"),
    ("slight_left", "nav_direction_continue_slight_left"),
    ("left", "nav_direction_continue_left"),
    ("slight_right", "nav_direction_continue_slight_right"),
    ("right", "nav_direction_continue_right"),
    ("uturn", "nav_continue_uturn"),
)


def load_source():
    selection = json.loads((SOURCE / "selection.json").read_text())
    font = TTFont(SOURCE / "gps-signs.ttf")
    cmap = {c: g for c, g in font.getBestCmap().items() if c >= 0xE000}
    mapped = {}
    glyph_set = font.getGlyphSet()
    for icon in selection["icons"]:
        prop = icon["properties"]
        codes = prop.get("codes", [prop["code"]])
        if not codes or codes[0] != prop["code"]:
            raise ValueError("Invalid primary layer code: " + prop["name"])
        paths = icon["icon"]["paths"]
        if len(codes) > 1 and len(codes) != len(paths):
            raise ValueError("Layer count mismatch: " + prop["name"])
        for index, code in enumerate(codes):
            if code in mapped or code not in cmap:
                raise ValueError("Duplicate or missing font code: " + hex(code))
            mapped[code] = prop["name"]
            # Confirm the source outline bounds, not just consecutive code numbers.
            source_bounds = BoundsPen(None)
            pen = TransformPen(source_bounds, (1, 0, 0, -1, 0, font["hhea"].ascent))
            for path in ([paths[index]] if len(codes) > 1 else paths):
                parse_path(path, pen)
            actual_bounds = BoundsPen(glyph_set)
            glyph_set[cmap[code]].draw(actual_bounds)
            if (source_bounds.bounds is None or actual_bounds.bounds is None or
                    any(abs(a - b) > 1.5 for a, b in
                        zip(source_bounds.bounds, actual_bounds.bounds))):
                raise ValueError("TTF/selection outline mismatch: " + hex(code))
    if set(mapped) != set(cmap) or len(mapped) != 46 or len(selection["icons"]) != 35:
        raise ValueError("Expected complete 35-icon / 46-code source pair")
    return selection


def mask_for(code):
    font = ImageFont.truetype(str(SOURCE / "gps-signs.ttf"), FONT_SIZE)
    # Render the real TTF and crop transparent bearings, not SVG/PNG substitutes.
    raster = Image.new("L", (FONT_SIZE * 3, FONT_SIZE * 3))
    ImageDraw.Draw(raster).text((FONT_SIZE, FONT_SIZE), chr(code), font=font, fill=255)
    bounds = raster.getbbox()
    if bounds is None:
        raise ValueError("Empty active glyph: " + hex(code))
    glyph = raster.crop(bounds)
    # Fit only if necessary. All active glyphs use the same em size.
    glyph.thumbnail((SIZE - 8, SIZE - 8), Image.Resampling.LANCZOS)
    mask = Image.new("L", (SIZE, SIZE))
    mask.paste(glyph, ((SIZE - glyph.width) // 2, (SIZE - glyph.height) // 2))
    return mask.point(lambda value: 255 if value >= 128 else 0)


def packed_mask(mask):
    data = bytearray()
    for y in range(SIZE):
        for x in range(0, SIZE, 8):
            value = 0
            for bit in range(8):
                if mask.getpixel((x + bit, y)):
                    value |= 0x80 >> bit
            data.append(value)
    return bytes(data)


def make_outputs(selection):
    icons = {icon["properties"]["name"]: icon for icon in selection["icons"]}
    license_text = (FIRMWARE / "LICENSE-font.txt").read_text().strip()
    hashes = {name: hashlib.sha256((SOURCE / name).read_bytes()).hexdigest()
              for name in ("gps-signs.ttf", "selection.json")}
    header = [
        "// Generated by scripts/generate-beeline-font.py; do not edit masks.",
        "// Rasterized from the user-provided IcoMoon TTF, NOT the PNG/SVG archive.",
        "// Source sha256: " + json.dumps(hashes, sort_keys=True),
        "/*\n" + license_text + "\n*/",
        "#pragma once", "#include <stdint.h>", "#include <pgmspace.h>",
        "namespace NavigationFont {",
        f"static constexpr int16_t kWidth = {SIZE}, kHeight = {SIZE};",
        "static constexpr uint8_t kCount = 6;",
        "static constexpr uint16_t kBytesPerIcon = kWidth * kHeight / 8;",
        "static const uint8_t kMasks[kCount][kBytesPerIcon] PROGMEM = {",
    ]
    codes = []
    for command, name in ACTIVE:
        prop = icons[name]["properties"]
        if len(prop.get("codes", [prop["code"]])) != 1:
            raise ValueError("Active maneuver unexpectedly needs multiple layers")
        code = prop["code"]
        codes.append(code)
        data = packed_mask(mask_for(code))
        if len(data) != SIZE * SIZE // 8 or not any(data):
            raise ValueError("Invalid packed glyph")
        header.append(f"  {{ // {command}: U+{code:04X} {name}")
        for offset in range(0, len(data), 32):
            header.append("    " + ", ".join(f"0x{b:02X}" for b in data[offset:offset + 32]) + ",")
        header.append("  },")
    header += ["};", "static constexpr uint16_t kCodepoints[kCount] = {" +
               ", ".join(f"0x{c:04X}" for c in codes) + "};",
               'static_assert(sizeof(kMasks) == 6912, "Unexpected icon flash budget");',
               "} // namespace NavigationFont", ""]
    csv_text = io.StringIO()
    writer = csv.writer(csv_text, lineterminator="\n")
    writer.writerow(["codepoint", "icone_icomoon", "camada", "camadas_no_ttf",
                     "preenchimento_original", "comando_firmware"])
    active_names = {name: command for command, name in ACTIVE}
    for icon in selection["icons"]:
        prop = icon["properties"]
        code_list = prop.get("codes", [prop["code"]])
        attrs = icon["icon"].get("attrs", [])
        for i, code in enumerate(code_list):
            fill = attrs[i].get("fill", "") if i < len(attrs) else ""
            writer.writerow([f"U+{code:04X}", prop["name"], i + 1, len(code_list),
                             fill, active_names.get(prop["name"], "")])
    return {
        FIRMWARE / "navigation-font.h": "\n".join(header),
        ROOT / "docs/firmware-font-codes.csv": csv_text.getvalue(),
    }


def preview(selection):
    out = ROOT / "generated-artifacts"
    out.mkdir(exist_ok=True)
    label = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 12)
    face = ImageFont.truetype(str(SOURCE / "gps-signs.ttf"), 76)
    cols, width, height = 5, 190, 155
    sheet = Image.new("RGB", (cols * width, 7 * height), "#191d22")
    draw = ImageDraw.Draw(sheet)
    for index, icon in enumerate(selection["icons"]):
        x, y = (index % cols) * width, (index // cols) * height
        prop = icon["properties"]
        codes = prop.get("codes", [prop["code"]])
        for layer, code in enumerate(codes):
            fill = icon["icon"]["attrs"][layer].get("fill", "") if len(codes) > 1 else ""
            color = "#9ba2aa" if fill == "rgb(128, 128, 128)" else "#f5cc43"
            draw.text((x + (width - 76) // 2, y + 3), chr(code), font=face, fill=color)
        name = prop["name"].removeprefix("nav_")
        # Wrap long names without omitting part of their identity.
        split = name.rfind("_", 0, 24) if len(name) > 23 else -1
        lines = [name] if split < 0 else [name[:split], name[split + 1:]]
        for line, text in enumerate(lines):
            draw.text((x + width // 2, y + 93 + line * 15), text, font=label,
                      anchor="mt", fill="#eeeeee")
        codes_label = "/".join(f"{code:04X}" for code in codes)
        draw.text((x + width // 2, y + 133), codes_label, font=label,
                  anchor="mt", fill="#aab1ba")
    sheet.save(out / "gps-signs-confirmados.png")
    # The six masks below are exactly those packed into the firmware header.
    active_sheet = Image.new("RGB", (3 * 200, 2 * 138), "#212021")
    draw = ImageDraw.Draw(active_sheet)
    icons = {i["properties"]["name"]: i for i in selection["icons"]}
    for index, (command, name) in enumerate(ACTIVE):
        x, y = index % 3 * 200, index // 3 * 138
        code = icons[name]["properties"]["code"]
        active_sheet.paste("#f5d541", (x + 52, y + 4, x + 148, y + 100), mask_for(code))
        draw.text((x + 100, y + 109), f"{command} / {code:04X}", font=label,
                  anchor="mt", fill="white")
    active_sheet.save(out / "firmware-ttf-seis-manobras.png")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--preview", action="store_true")
    args = parser.parse_args()
    selection = load_source()
    for path, text in make_outputs(selection).items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit("Outdated generated file: " + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.preview:
        preview(selection)
    print("OK: 35 icons / 46 codes match TTF outline bounds; 6 active masks = 6912 flash bytes")


if __name__ == "__main__":
    main()
